#!/usr/bin/env node
// Writes the generated reference pages in docs/build/reference/ from the code itself, so they can't drift:
//
//   mcp.md     the MCP tools, as a running Parachute server lists them (tools/list and vault-info {help}), at each level
//   applet.md  the app's applet guide, docs/WRITE-AN-APPLET.md from ParachuteComputer/parachute at a commit
//
//   npm run docs:sync -- mcp     PARACHUTE_HUB=http://127.0.0.1:1939 PARACHUTE_VAULT=home PARACHUTE_KEY=<an admin key>
//                                (a throwaway server is best: the page names no records, only tools)
//   npm run docs:sync -- applet  PARACHUTE_APP_REF=<commit or branch, default next>
//
// Each page says where it came from. Edit the source, not the page.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(import.meta.dirname, "..", "docs", "build", "reference");
const which = process.argv[2];

const front = (o) => `---\n${Object.entries(o).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join("\n")}\n---\n`;

async function mcp() {
  const hub = (process.env.PARACHUTE_HUB ?? "").replace(/\/+$/, "");
  const vault = process.env.PARACHUTE_VAULT ?? "home";
  const key = process.env.PARACHUTE_KEY;
  if (!hub || !key) throw new Error("set PARACHUTE_HUB and PARACHUTE_KEY (an admin key for PARACHUTE_VAULT)");
  let id = 0;
  const call = async (method, params) => {
    const r = await fetch(`${hub}/vault/${vault}/mcp`, {
      method: "POST",
      headers: { authorization: `Bearer ${key}`, "content-type": "application/json", accept: "application/json, text/event-stream" },
      body: JSON.stringify({ jsonrpc: "2.0", id: ++id, method, params }),
    });
    const b = await r.json();
    if (b.error) throw new Error(`${method}: ${b.error.message}`);
    return b.result;
  };
  const init = await call("initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "docs-sync", version: "1" } });
  const version = init.serverInfo?.version ?? "?";
  const health = await fetch(`${hub}/health`).then((r) => r.json()).catch(() => ({}));
  // PARACHUTE_CORE_REF names the source when the server runs a branch, not a release (e.g. "next at 6b2d4ca").
  const release = [health.version ?? "unknown", process.env.PARACHUTE_CORE_REF].filter(Boolean).join(", ");
  const { tools } = await call("tools/list", {});
  const fresh = tools.filter((t) => !t.description.startsWith("Deprecated"));
  const old = tools.filter((t) => t.description.startsWith("Deprecated"));
  const LEVEL = { "create-record": "write", "update-record": "write", "delete-record": "write", "manage-types": "admin", "manage-keys": "admin" };
  const lines = [
    front({
      title: "MCP tools",
      summary: "Every tool the Parachute MCP lists, with what it needs and every parameter. Generated from a running server.",
      door: "build",
      order: 20,
      nav: "Reference: MCP tools",
      checked: `generated by scripts/docs-sync.mjs from tools/list and vault-info {help} on parachute-core ${release}`,
    }),
    "The tools a connection sees depend on its level ([Keys](/docs/build/keys-and-scopes/)). Descriptions are the server's own words; the parameter tables come from `vault-info { \"help\": \"<tool>\" }`.",
    "",
    "| Tool | Level | What it does |",
    "|---|---|---|",
    ...fresh.map((t) => `| \`${t.name}\` | ${LEVEL[t.name] ?? "read"} | ${t.description.split("\n")[0].replace(/\|/g, "\\|")} |`),
    "",
    `Still answering through 0.9, gone in 1.0: ${old.map((t) => `\`${t.name}\``).join(", ")}. Each says what replaced it.`,
    "",
  ];
  for (const t of fresh) {
    const help = await call("tools/call", { name: "vault-info", arguments: { help: t.name } }).then((r) => JSON.parse(r.content[0].text)).catch(() => null);
    const props = help?.parameters?.properties ?? t.inputSchema?.properties ?? {};
    lines.push(`## ${t.name}`, "", t.description, "");
    const names = Object.keys(props);
    if (names.length) {
      lines.push("| Parameter | Type | What it is |", "|---|---|---|");
      for (const n of names) {
        const p = props[n] ?? {};
        const type = p.type ?? (p.oneOf ? p.oneOf.map((o) => o.type).join(" or ") : p.enum ? "one of" : "");
        const d = String(p.description ?? (p.enum ? p.enum.join(", ") : "")).replace(/\s+/g, " ").replace(/\|/g, "\\|").slice(0, 400);
        lines.push(`| \`${n}\` | ${type} | ${d} |`);
      }
      lines.push("");
    }
    if (help?.actions) lines.push(`Actions: ${Object.keys(help.actions).map((a) => `\`${a}\``).join(", ")}.`, "");
  }
  lines.push(`*Server ${version}, release ${release}. Regenerate with \`npm run docs:sync -- mcp\`.*`, "");
  writeFileSync(join(OUT, "mcp.md"), lines.join("\n"));
  console.log(`docs/build/reference/mcp.md: ${fresh.length} tools, ${old.length} old names, from ${release}`);
}

async function applet() {
  const ref = process.env.PARACHUTE_APP_REF ?? "next";
  const sha = await fetch(`https://api.github.com/repos/ParachuteComputer/parachute/commits/${ref}`, { headers: { accept: "application/vnd.github.sha" } }).then((r) => r.text());
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error(`no commit for ${ref}`);
  const raw = await fetch(`https://raw.githubusercontent.com/ParachuteComputer/parachute/${sha}/docs/WRITE-AN-APPLET.md`).then((r) => {
    if (!r.ok) throw new Error(`WRITE-AN-APPLET.md at ${sha}: ${r.status}`);
    return r.text();
  });
  const blob = (p) => `https://github.com/ParachuteComputer/parachute/blob/${sha}/${p}`;
  const body = raw
    .replace(/^# .*\n+/, "") // the layout prints the title
    // links to the repo's own files go to them on GitHub, at this commit
    .replace(/\]\((?!https?:|#|\/)([^)#]+)(#[^)]*)?\)/g, (_m, p, h = "") => `](${blob(new URL(p, "https://x/docs/").pathname.slice(1))}${h})`)
    // and paths in backticks that name files stay as text
    ;
  const page =
    front({
      title: "Applet reference",
      summary: "The whole manifest, every kit call and part, saved state, links, and worked examples. Copied from the app's own guide.",
      door: "build",
      order: 21,
      nav: "Reference: applets",
      checked: `copied by scripts/docs-sync.mjs from ParachuteComputer/parachute docs/WRITE-AN-APPLET.md at ${sha.slice(0, 7)}`,
    }) +
    `*This page is the app's own guide, [docs/WRITE-AN-APPLET.md](${blob("docs/WRITE-AN-APPLET.md")}) at ${sha.slice(0, 7)}, copied as it is. In it, a bundle is still called an "app". The short version: [Make an applet](/docs/build/make-an-applet/).*\n\n` +
    body;
  writeFileSync(join(OUT, "applet.md"), page);
  console.log(`docs/build/reference/applet.md: from ${sha}`);
}

if (which === "mcp") await mcp();
else if (which === "applet") await applet();
else {
  console.error("usage: docs-sync.mjs mcp|applet");
  process.exit(2);
}
